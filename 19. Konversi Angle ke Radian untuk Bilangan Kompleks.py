import cmath
import math

angle_degrees = 45
angle_radians = math.radians(angle_degrees)
z = cmath.rect(1, angle_radians)
print("Bilangan kompleks dari sudut 45 derajat:", z)
# Fungsi: Mengonversi sudut dari derajat ke radian untuk menghasilkan bilangan kompleks.
# Kondisi: Ketika Anda berurusan dengan representasi sudut dalam pekerjaan kompleks.
